package link

import (
	"math/rand"
	"time"
)

const charset = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"

func NewLink(longURL string) Link {
	return Link{
		ShortCode: generateCode(6),
		LongURL:   longURL,
		CreatedAt: time.Now(),
	}
}

func generateCode(n int) string {
	b := make([]byte, n)
	for i := range b {
		b[i] = charset[rand.Intn(len(charset))]
	}
	return string(b)
}
